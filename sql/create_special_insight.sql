-- Special Insight articles (e.g. gold). Applied 2026-10-12 as migration create_special_insight.
-- Same columns as monthly_asset_class_outlook plus asset_type, so the AI pipeline can write
-- the same payload and only switch the target table. asset_type says which special paper it is.
create table public.special_insight (
  id bigint generated by default as identity primary key,
  path text unique,
  asset_type text not null,
  hs_name text,
  week_slug text,
  main_title text,
  page_subtitle text,
  sub_title text,
  page_date date,
  week_start_date date,
  week_end_date date,
  cover_image jsonb,
  description text,
  ai_summary text,
  body text,
  is_published boolean default true
);
comment on table public.special_insight is 'Special Insight articles (e.g. gold). Same columns as monthly_asset_class_outlook plus asset_type.';
create index special_insight_page_date_idx on public.special_insight (page_date desc);
alter table public.special_insight enable row level security;
create policy "public read access" on public.special_insight for select to anon, authenticated using (true);

-- Test data: copies of the existing gold articles (2026-07-01-gold, 2026-10-01-gold);
-- monthly_asset_class_outlook is left untouched.
